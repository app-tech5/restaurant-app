#!/usr/bin/env node
/**
 * Start Expo with an explicit demo/live mode that wins over `.env`.
 *
 * Expo loads `.env` then `.env.local` (local wins). Shell `EXPO_PUBLIC_*=`
 * is not always applied to the Metro bundle, so we write `.env.local` and
 * set process.env before spawning `expo start`.
 *
 *   node scripts/expo-start-mode.js demo --localhost
 *   node scripts/expo-start-mode.js live --localhost
 */
const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

const modeArg = String(process.argv[2] || 'demo').toLowerCase();
const isLive = modeArg === 'live' || modeArg === 'false';
const expoArgs = process.argv.slice(3);
const demoValue = isLive ? 'false' : 'true';
const root = path.join(__dirname, '..');
const envLocalPath = path.join(root, '.env.local');

const banner = `# Generated by scripts/expo-start-mode.js (${isLive ? 'live' : 'demo'}) — do not edit by hand.\n`;
fs.writeFileSync(
  envLocalPath,
  `${banner}EXPO_PUBLIC_DEMO_MODE=${demoValue}\n`,
  'utf8'
);

const env = {
  ...process.env,
  EXPO_PUBLIC_DEMO_MODE: demoValue,
};

console.log(`[expo-start-mode] DEMO_MODE=${demoValue} (${isLive ? 'live API writes' : 'demo local writes'})`);
console.log(`[expo-start-mode] wrote ${path.basename(envLocalPath)}`);

const child = spawn('npx', ['expo', 'start', ...expoArgs], {
  cwd: root,
  env,
  stdio: 'inherit',
  shell: true,
});

child.on('exit', (code, signal) => {
  if (signal) process.kill(process.pid, signal);
  process.exit(code == null ? 1 : code);
});
